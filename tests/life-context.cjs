const fs=require('node:fs'),assert=require('node:assert/strict');
const h=fs.readFileSync('index.html','utf8');
assert.equal((h.match(/class="cyf-life-context"/g)||[]).length,1);
assert.ok(h.indexOf('class="cyf-life-context"')>h.indexOf('id="preview-monthly"'));
const band=h.match(/<section class="cyf-life-context"[\s\S]*?<\/section>/)?.[0];
assert.ok(band,'Editorial band remains separate from tools');
const images=[...band.matchAll(/<img\b[^>]*>/g)];
assert.equal(images.length,1,'One editorial image, not duplicated desktop/mobile downloads');
const img=images[0][0],attr=name=>img.match(new RegExp('\\b'+name+'="([^"]*)"'))?.[1];
const src=new URL(attr('src'));
assert.equal(src.protocol,'https:');assert.equal(src.hostname,'images.unsplash.com');
assert.ok(src.pathname.startsWith('/photo-'),'Photo source retained, not a tracker');
assert.equal(src.searchParams.get('w'),'1200');
assert.equal(attr('loading'),'lazy');assert.equal(attr('decoding'),'async');
assert.equal(attr('referrerpolicy'),'no-referrer');
assert.equal(attr('width'),'1200');assert.equal(attr('height'),'800');
assert.equal(attr('alt'),'Sunglasses resting on beach sand with the ocean in the background','Alternative text matches the inspected current photograph');
assert.ok(band.includes('Illustrative photo, not a customer testimonial.'));
assert.ok(!/AI-generated|not licensed stock|licensed stock|model.released/i.test(band),'No stale asset type or unverified rights claims');
assert.ok(!/<link[^>]*rel="preload"[^>]*photo-1473496169904/.test(h));
const css=fs.readFileSync('assets/life-context.css','utf8');
assert.match(css,/\.cyf-life-context img\{[^}]*width:100%;height:auto;aspect-ratio:3\/2/);
assert.match(css,/@media\(max-width:640px\)/);
